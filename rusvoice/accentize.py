"""Авто-расстановка ударений для русского TTS через RUAccent (Den4ikAI/ruaccent,
Apache-2.0). Ставит '+' ПЕРЕД ударной гласной — конвенция совпадает с F5-accent
(который метки уважает). ТОЛЬКО для clone-пути: edge '+' игнорит.
Опциональный модуль (à la pronounce/music): нет RUAccent / упал → текст как есть.
env ACCENTIZE=0 — байпас, RUACCENT_MODEL — размер омограф-модели."""
import os
import re

_ACC = {"fn": None, "tried": False, "size": None}

# Размер омограф-модели. Был зашит `turbo` — САМАЯ старая; библиотека к 1.5.8 по умолчанию
# грузит turbo2, а лучший из доступных — turbo3.1. Замер на живых фразах ролика:
# turbo «кот+орая +уже +есть» (у́же = сравнительная степень «узкий» — слышно, что не то),
# turbo3.1 «кот+орая уж+е +есть» — верно. Разовая докачка ~155с, дальше из кэша.
DEFAULT_MODEL = "turbo3.1"

# RUAccent заодно ёфицирует (е→ё) — нетто-полезно (всё/ещё/актёр), НО изредка ложно
# срабатывает на омонимах. Канонная осечка: «небо/sky» → «нёбо/палатум». Узкий курируемый
# revert ё→е для словоформ, где ёфикация заведомо ложна в нашем домене.
_YO_FALSE_POSITIVES = frozenset({
    "небо", "неба", "небе", "небом", "небеса", "небесам", "небесами", "небесах",
})
_WORD_RE = re.compile(r"[А-Яа-яЁё+]+")

# Курируемые правки ПОВЕРХ модели: база (без '+', ё→е, нижний регистр) → верная форма.
# Нужны там, где ошибается и лучшая модель, а ошибка слышна. Ё-ревертом такое не лечится:
# у «само+ё» неверна и буква, и позиция ударения (верно «с+амое»).
# Замерено на реальных фразах 02.08.2026; список расширяется по мере находок, а не «на всякий».
_FIXUPS = {
    "самое": "с+амое", "самого": "с+амого", "самому": "с+амому",
    "самом": "с+амом", "самою": "с+амою",
}


# Гласные — для подсчёта слогов (см. _strip_mono).
_VOWELS = frozenset("аеёиоуыэюяАЕЁИОУЫЭЮЯ")


# Версия правил акцентизатора в ключе аудио-кэша движка.
#
# ⚠️ Живёт ЗДЕСЬ, потому что описывает поведение этого файла. Раньше константа стояла
# двумя копиями в движке (`html_reel.ACCENT_RULES_VERSION` и `footage._ACCENT_RULES_VERSION`),
# и правило было «поменял поведение — подними номер РУКАМИ В ДВУХ МЕСТАХ». Копия, которую
# надо помнить, однажды не поднимается: ровно так `html_reel` завёл `|acc`, а зеркало нет,
# и per-beat футаж молча выродился в один клип. Теперь копий нет — движок читает отсюда.
#
# Поднимать, когда меняется ЗВУК: v2 (26.08.2026) — снятие «+» с односложных слов.
RULES_VERSION = "2"


def _strip_mono(tok: str) -> str:
    """Снять '+' с ОДНОСЛОЖНОГО слова: метка там не несёт информации, а F5 её отыгрывает.

    Причина правки (Илья 26.08.2026, «нейрослоп — проблемы с ударением»). RUAccent размечает
    и служебную односложную мелочь: «Т+ы не з+анят. Т+ы разбаз+арен», «кто н+е прос+ил»,
    «д+о сих п+ор». В слове с ОДНОЙ гласной ударение и так безальтернативно — метка не
    сообщает модели ничего нового. Но F5 читает '+' как реальный нажим, и речь начинает
    молотить каждое второе слово: это и слышно как машинность, а не как ударение не на том
    слоге. Снятие метки не может сместить ударение — смещать в односложном слове некуда.
    Заодно уходят две реальные ошибки модели на клитиках: «не с ч+ем» (верно «н+е с чем») и
    «д+о сих пор» (верно «до сих п+ор») — обе лечатся не подсказкой, а молчанием.
    ⚠️ Ударения АВТОРА это не трогает: _merge_author_marks накладывается ПОСЛЕ и возвращает
    их поверх — ручная метка на «н+е» остаётся осознанным акцентом.
    """
    return tok.replace("+", "") if sum(c in _VOWELS for c in tok) <= 1 else tok


def _base(tok: str) -> str:
    return tok.replace("+", "").replace("ё", "е").replace("Ё", "Е").lower()


def _restore_case(src: str, form: str) -> str:
    """Форма из словаря — в нижнем регистре; вернуть регистр исходного слова."""
    if src[:1].isupper():
        i = 1 if form[:1] == "+" else 0      # заглавная — на ПЕРВУЮ букву, не на ударную
        if i < len(form):
            return form[:i] + form[i].upper() + form[i + 1:]
    return form


def _post_fix(text: str) -> str:
    """Ложная ёфикация, курируемые правки, снятие меток с односложных. Регистр сохранён."""
    def repl(m):
        tok = m.group(0)
        base = _base(tok)
        if base in _FIXUPS:
            return _restore_case(tok, _FIXUPS[base])
        if base in _YO_FALSE_POSITIVES:
            tok = tok.replace("ё", "е").replace("Ё", "Е")
        return _strip_mono(tok)
    return _WORD_RE.sub(repl, text)


def _merge_author_marks(src: str, out: str) -> str:
    """Ударения, поставленные АВТОРОМ в сценарии, сильнее модели.

    Модель не знает контекста ролика и на омографах ошибается («замок» она даёт одинаково
    и для двери, и для холма — проверено на обеих моделях). Единственный надёжный рычаг —
    рука автора, и она обязана переживать прогон акцентизатора. Сопоставляем по номеру
    слова: ёфикация слов не расщепляет, так что нумерация совпадает.
    """
    if "+" not in src:
        return out
    src_toks = _WORD_RE.findall(src)
    if len(src_toks) != len(_WORD_RE.findall(out)):
        return out                       # разъехалась разметка — не рискуем, отдаём модель
    it = iter(range(len(src_toks)))

    def repl(m):
        i = next(it)
        return src_toks[i] if "+" in src_toks[i] else m.group(0)
    return _WORD_RE.sub(repl, out)


def _load_accentizer():
    """Ленивая загрузка RUAccent → callable(text)->text с '+'. Нет пакета → None."""
    size = os.environ.get("RUACCENT_MODEL") or DEFAULT_MODEL
    if _ACC["tried"] and _ACC["size"] == size:
        return _ACC["fn"]
    _ACC["tried"] = True
    _ACC["size"] = size
    try:
        from ruaccent import RUAccent
        a = RUAccent()
        a.load(omograph_model_size=size, use_dictionary=True)
        _ACC["fn"] = lambda t: a.process_all(t)
    except Exception:
        _ACC["fn"] = None
    return _ACC["fn"]


def accentize_ru(text: str) -> str:
    """Текст → текст с '+' перед ударными гласными. Graceful: нет RUAccent → как есть.
    env ACCENTIZE=0 — байпас. Ударения автора (уже стоящие '+') не перетираются."""
    if not text or os.environ.get("ACCENTIZE", "1") == "0":
        return text
    fn = _load_accentizer()
    if fn is None:
        return text
    try:
        return _merge_author_marks(text, _post_fix(fn(text)))
    except Exception:
        return text
