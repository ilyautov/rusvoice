# -*- coding: utf-8 -*-
"""Омографы: слова, где ударение решает СМЫСЛ, а не словарь.

Замер по корпусу (456 сценариев, 6791 реплика, 07.09.2026) поставил точку в вопросе
«почему словарь ударений такой тонкий». Оказалось, что RUAccent ставит метку в 98.3%
многосложных слов, а из оставшихся 1.7% почти всё — служебные слова, которые F5 читает
верно. То есть **пропущенных меток проблемы нет**.

Проблема в другом, и «нет метки» её не ловит вовсе: метка СТОИТ, но не та.

    «Потом становится легко»          → RUAccent: п+отом  (то есть «облился по́том»)
    «самая большая языковая модель»   → RUAccent: б+ольшая (то есть «бо́льшая часть»)
    «Между нодами рисуются стрелки»   → RUAccent: стрелк+и (родительный от «стрело́к»)

⚠️ Словарём это НЕ лечится. Словарь ударений — глобальная замена «слово → слово», а здесь
одно и то же слово в двух соседних репликах читается по-разному: «за́мок на горе» и «замо́к
щёлкнул в двери». Записав «большая → больш+ая», мы почин­им пятьдесят реплик и сломаем
«бо́льшая часть» во всех будущих. Инструмент нужен другой: не замена, а **предупреждение
автору**, который единственный знает, что имел в виду, — и у которого есть чем ответить,
метка «+» прямо в тексте сценария.

Чтобы предупреждение не превратилось в шум, срабатываем НЕ на каждом омографе. В корпусе
«уже́» встретилось 273 раза, «со́рок» — 133, и оба раза RUAccent прав: у этих пар одно
чтение подавляюще частотнее. Поэтому таблица хранит РЕДКОЕ чтение, и линт говорит только
тогда, когда акцентизатор выбрал именно его.
"""
from __future__ import annotations

import re

# форма → (редкая разметка, что она значит, частая разметка)
# Пары отобраны по одному признаку: одно чтение в живой русской речи подавляюще частотнее,
# поэтому выбор редкого — сигнал. Симметричные пары (за́мок/замо́к, сто́ит/стои́т) сюда НЕ
# берём: RUAccent на них в корпусе не ошибся ни разу, а предупреждение было бы шумом.
RARE = {
    "потом":   ("п+отом", "творительный от «пот»", "пот+ом"),
    "большая": ("б+ольшая", "«бо́льшая часть»", "больш+ая"),
    "стрелки": ("стрелк+и", "родительный от «стрело́к»", "стр+елки"),
    "целую":   ("цел+ую", "«я целу́ю»", "ц+елую"),
    "мою":     ("м+ою", "«я мо́ю»", "мо+ю"),
    "дорога":  ("д+орога", "краткое «дорога́» — «она мне до́рога»", "дор+ога"),
    "вести":   ("в+ести", "«но́вости»", "вест+и"),
    "уже":     ("+уже", "сравнительная от «у́зкий»", "уж+е"),
    "сорок":   ("сор+ок", "родительный от «соро́ка»-птицы", "с+орок"),
    "плачу":   ("пл+ачу", "«я пла́чу» слезами", "плач+у"),
    "пили":    ("пил+и", "повелительное от «пили́ть»", "п+или"),
    "духи":    ("д+ухи", "множественное от «дух»", "дух+и"),
    "мука":    ("м+ука", "страдание", "мук+а"),
    "белки":   ("б+елки", "родительный от «белка́»-зверька", "белк+и"),
    "полки":   ("полк+и", "воинские части", "п+олки"),
    "атлас":   ("атл+ас", "ткань", "+атлас"),
    "орган":   ("орг+ан", "музыкальный инструмент", "+орган"),
}

# ⚠️ Слова с ЕДИНСТВЕННЫМ верным чтением, которые RUAccent оставляет без метки, сюда НЕ
# попадают — им место в словаре ударений, он их чинит сам и без участия автора. Так ушла
# «среда» (10 вхождений в корпусе без метки): именительный «среда́» верен и для дня недели,
# и для окружения, значит глобальная замена безопасна. Здесь остаётся только то, что
# глобально решить НЕЛЬЗЯ.


def _tokens(text: str):
    return re.findall(r"[А-Яа-яЁё+]+", text)


def author_marked(source: str, word: str) -> bool:
    """Автор сам поставил метку на это слово в тексте сценария → молчим.

    ⚠️ Именно это и есть ответ на предупреждение: метка «+» прямо в `vo` переживает
    любой акцентизатор. Ругаться на разрешённую неоднозначность — верный способ приучить
    пролистывать вывод целиком."""
    for tok in _tokens(source):
        if "+" in tok and tok.replace("+", "").lower() == word:
            return True
    return False


def scan(source: str, accented: str) -> list:
    """Список (слово, выбранная_разметка, объяснение, подсказка). Пусто — вопросов нет."""
    out = []
    marked = [t for t in _tokens(accented)]
    for tok in marked:
        bare = tok.replace("+", "").lower()
        low = tok.lower()
        if bare in RARE:
            rare, gloss, common = RARE[bare]
            if low == rare and not author_marked(source, bare):
                out.append((bare, rare, f"выбрано редкое чтение — {gloss}",
                            f"если имелось в виду обычное, поставь метку: {common}"))
    return out
